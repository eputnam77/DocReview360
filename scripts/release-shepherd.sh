#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# release-shepherd.sh — Local release shepherd loop.
#
# Reads RELEASE_CHECKLIST.md, picks the first unchecked item, runs a quick
# test smoke, and writes a short outcome report under artifacts/automation/.
#
# Usage:
#   ./scripts/release-shepherd.sh
#
# Output artifact:
#   artifacts/automation/release-shepherd-<timestamp>.md

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CHECKLIST="${REPO_ROOT}/RELEASE_CHECKLIST.md"
ARTIFACTS_DIR="${REPO_ROOT}/artifacts/automation"
TIMESTAMP="$(date -u +%Y%m%dT%H%M%SZ)"
REPORT="${ARTIFACTS_DIR}/release-shepherd-${TIMESTAMP}.md"

# ── Lockfile (only 1 shepherd loop at a time) ────────────────────────────────
LOCKFILE="${REPO_ROOT}/.shepherd.lock"
if [ -e "${LOCKFILE}" ]; then
    echo "ERROR: Another shepherd loop is running (lockfile: ${LOCKFILE})." >&2
    echo "       Remove the lockfile if the previous run crashed." >&2
    exit 1
fi
trap 'rm -f "${LOCKFILE}"' EXIT
echo "$$" > "${LOCKFILE}"

# ── Ensure artifacts directory exists ────────────────────────────────────────
mkdir -p "${ARTIFACTS_DIR}"

# ── Find first unchecked item ─────────────────────────────────────────────────
# Match lines of the form: - [ ] <item text>
SELECTED_LINE=""
SELECTED_LINENO=""

while IFS= read -r line; do
    SELECTED_LINENO=$((SELECTED_LINENO + 1))
    if [[ "${line}" =~ ^[[:space:]]*-[[:space:]]\[[[:space:]]\][[:space:]](.+)$ ]]; then
        SELECTED_LINE="${BASH_REMATCH[1]}"
        break
    fi
done < <(grep -n '^\s*- \[ \]' "${CHECKLIST}" | head -1)

# Re-do: simpler extraction
SELECTED_LINE=""
SELECTED_LINENO=""
GREP_RESULT="$(grep -n '^\s*- \[ \]' "${CHECKLIST}" | head -1 || true)"

if [ -z "${GREP_RESULT}" ]; then
    echo "No unchecked items found in ${CHECKLIST}. All done!"
    cat > "${REPORT}" <<EOF
# Release Shepherd Report

**Timestamp:** ${TIMESTAMP}
**Status:** No unchecked items found.

All items in RELEASE_CHECKLIST.md appear to be checked off. Release may be ready.

**Recommended next action:** Review completed items and confirm release readiness.
EOF
    echo "Report written to: ${REPORT}"
    exit 0
fi

SELECTED_LINENO="$(echo "${GREP_RESULT}" | cut -d: -f1)"
SELECTED_LINE="$(echo "${GREP_RESULT}" | cut -d: -f2- | sed 's/^\s*- \[ \] //')"

echo "=== Release Shepherd ==="
echo "Timestamp  : ${TIMESTAMP}"
echo "Checklist  : ${CHECKLIST}"
echo "Selected   : Line ${SELECTED_LINENO}: ${SELECTED_LINE}"
echo ""

# ── Run quick test smoke ──────────────────────────────────────────────────────
echo "Running: pytest -q --tb=no -x -q"
TEST_OUTPUT=""
TEST_EXIT=0

cd "${REPO_ROOT}"

# Activate venv if present
if [ -f ".venv/bin/activate" ]; then
    # shellcheck disable=SC1091
    source ".venv/bin/activate"
fi

TEST_OUTPUT="$(DOCREVIEW360_ENV=dev pytest -q --tb=no -x -q 2>&1 | head -20)" || TEST_EXIT=$?

echo "Test exit code: ${TEST_EXIT}"
echo ""
echo "Test output (first 20 lines):"
echo "${TEST_OUTPUT}"
echo ""

# ── Determine recommended next action ────────────────────────────────────────
if [ "${TEST_EXIT}" -eq 0 ]; then
    RECOMMENDATION="Tests are passing. Review the selected checklist item and implement a minimal change. Re-run this script after making changes to verify."
else
    RECOMMENDATION="Tests are currently failing (exit code ${TEST_EXIT}). Investigate the failing tests before tackling new checklist items. Run: DOCREVIEW360_ENV=dev pytest -q --tb=short to see details."
fi

# ── Write report ──────────────────────────────────────────────────────────────
cat > "${REPORT}" <<EOF
# Release Shepherd Report

**Timestamp:** ${TIMESTAMP}
**Checklist:** ${CHECKLIST}

## Selected Item

- Line number: ${SELECTED_LINENO}
- Item text: ${SELECTED_LINE}

## Test Results

**Exit code:** ${TEST_EXIT}

\`\`\`
${TEST_OUTPUT}
\`\`\`

## Recommended Next Action

${RECOMMENDATION}

---
*Generated by scripts/release-shepherd.sh*
EOF

echo "Report written to: ${REPORT}"
