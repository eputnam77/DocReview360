"""Git hook utilities for validating patch emails.

This module provides a basic validation helper for `git send-email`.
It performs lightweight checks on the given patch text and returns
``True`` if no issues were detected. The function never raises so it can
be used in pre-send hooks without aborting unexpectedly.
"""

from __future__ import annotations

import re
from typing import Iterable


def _read_patch(path: str) -> str:
    """Return the patch contents from ``path`` if the file exists."""
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return fh.read()
    except FileNotFoundError:
        return ""


def _spell_errors(lines: Iterable[str]) -> int:
    """Return a count of obviously misspelled words.

    The check is intentionally naive to avoid heavy dependencies. It
    flags words consisting only of alphabetic characters longer than
    20 letters which rarely occur in normal prose.
    """
    count = 0
    for line in lines:
        for word in re.findall(r"[A-Za-z]{21,}", line):
            count += 1
    return count


def validate_patch(patch: str) -> bool:
    """Validate a patch string.

    Parameters
    ----------
    patch:
        The raw patch text as generated by ``git format-patch`` or
        similar commands.

    Returns
    -------
    bool
        ``True`` if the patch looks clean enough to be sent.

    The function checks for trailing whitespace, tab characters and
    performs a very small spelling sanity check. It is intentionally
    lenient and never raises; callers may inspect the boolean result if
    they want to abort sending the email.
    """
    lines = patch.splitlines()
    trailing_ws = any(line.rstrip() != line for line in lines)
    has_tabs = any("\t" in line for line in lines)
    spelling = _spell_errors(lines)
    return not (trailing_ws or has_tabs or spelling)


def main(path: str) -> int:
    """Entry point for the send-email hook."""
    patch = _read_patch(path)
    ok = validate_patch(patch)
    return 0 if ok else 1


if __name__ == "__main__":
    import sys

    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else ""))
